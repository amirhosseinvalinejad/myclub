const I18N_CACHE_KEY = "myclub-i18n-cache-v2";
let I18N_CACHE = {};

try {
  I18N_CACHE = JSON.parse(localStorage.getItem(I18N_CACHE_KEY) || "{}") || {};
} catch {
  I18N_CACHE = {};
}

function interpolate(value, vars) {
  let out = value;
  if (vars) {
    for (const [name, item] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(item));
    }
  }
  return out;
}

function currentLangCode() {
  return (document.documentElement.lang || "en").split("-")[0] || "en";
}

function t(key, vars) {
  const lang = currentLangCode();
  const english = I18N_EN[key] || key;
  const translated = lang === "en" ? english : (I18N_CACHE[lang] && I18N_CACHE[lang][key]) || english;
  return interpolate(translated, vars);
}

function translateServerError(message) {
  const key = SERVER_ERROR_KEYS[message];
  return key ? t(key) : message;
}

function persistI18nCache() {
  try {
    localStorage.setItem(I18N_CACHE_KEY, JSON.stringify(I18N_CACHE));
  } catch {
    // storage full
  }
}

async function ensureTranslations(lang, onProgress) {
  const code = (lang || "en").split("-")[0];
  if (!code || code === "en") {
    return;
  }
  I18N_CACHE[code] = I18N_CACHE[code] || {};
  const visible = [...document.querySelectorAll("[data-i18n]")]
    .map((el) => el.dataset.i18n)
    .filter(Boolean);
  const ordered = [...new Set([...visible, ...Object.keys(I18N_EN)])];
  const missing = ordered.filter((key) => I18N_EN[key] && !I18N_CACHE[code][key]);
  if (!missing.length) {
    return;
  }
  const chunkSize = 24;
  for (let i = 0; i < missing.length; i += chunkSize) {
    const slice = missing.slice(i, i + chunkSize);
    const texts = slice.map((key) => I18N_EN[key]);
    try {
      const response = await fetch("/api/translate", {
        method: "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ lang: code, texts }),
      });
      if (!response.ok) {
        break;
      }
      const data = await response.json();
      const translations = data.translations || [];
      slice.forEach((key, index) => {
        const translated = String(translations[index] || "").trim();
        if (translated) {
          I18N_CACHE[code][key] = translated;
        }
      });
      persistI18nCache();
      if (typeof onProgress === "function") {
        onProgress();
      }
    } catch {
      break;
    }
  }
}

function applyI18nElement(el) {
  const key = el.dataset.i18n;
  if (!key) {
    return;
  }
  const value = t(key);
  const attr = el.dataset.i18nAttr;
  if (attr) {
    el.setAttribute(attr, value);
    return;
  }
  if (el.tagName === "INPUT" || el.tagName === "TEXTAREA" || el.tagName === "SELECT") {
    if ("placeholder" in el) {
      el.placeholder = value;
    }
    return;
  }
  if (el.tagName === "TITLE") {
    document.title = value;
    return;
  }
  const skip = el.querySelector("[aria-hidden='true'], .nav-ico, .pm-dot");
  if (skip) {
    const nodes = [...el.childNodes].filter((node) => node.nodeType === Node.TEXT_NODE);
    if (nodes.length) {
      nodes[nodes.length - 1].textContent = ` ${value}`;
    } else {
      el.append(document.createTextNode(` ${value}`));
    }
    return;
  }
  el.textContent = value;
}
